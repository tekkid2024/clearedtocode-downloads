#!/usr/bin/env node
// Builds catalog.json and the download tables in the READMEs from
// apps/<id>/app.json plus this repository's GitHub Releases.
// A release belongs to an app when its tag is "<app id>-v<version>".
//
//   node scripts/build-catalog.mjs              fetch releases from the GitHub API
//   RELEASES_FILE=r.json node scripts/...       use a saved API response instead
//   GITHUB_TOKEN=...                            optional, raises the API rate limit
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = process.env.GITHUB_REPOSITORY || 'tekkid2024/clearedtocode-downloads';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- catalog:start (generated by scripts/build-catalog.mjs, do not edit by hand) -->';
const END = '<!-- catalog:end -->';

export function compareVersions(a, b) {
  const pa = a.split(/[.-]/).map(n => parseInt(n, 10) || 0);
  const pb = b.split(/[.-]/).map(n => parseInt(n, 10) || 0);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pa[i] || 0) - (pb[i] || 0);
    if (d) return d;
  }
  return 0;
}

export function loadApps(dir = path.join(root, 'apps')) {
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter(d => d.isDirectory() && fs.existsSync(path.join(dir, d.name, 'app.json')))
    .map(d => {
      const app = JSON.parse(fs.readFileSync(path.join(dir, d.name, 'app.json'), 'utf8'));
      if (app.id !== d.name) throw new Error(`apps/${d.name}/app.json: id must be "${d.name}"`);
      for (const key of ['title', 'summary', 'platform', 'category']) {
        if (!app[key]) throw new Error(`apps/${d.name}/app.json: missing "${key}"`);
      }
      return app;
    })
    .sort((a, b) => (a.order ?? 99) - (b.order ?? 99) || a.title.localeCompare(b.title));
}

function toRelease(r, version) {
  return {
    version,
    tag: r.tag_name,
    name: r.name || r.tag_name,
    publishedAt: r.published_at,
    prerelease: !!r.prerelease,
    url: r.html_url,
    assets: (r.assets || []).map(a => ({
      name: a.name,
      size: a.size,
      sha256: a.digest?.startsWith('sha256:') ? a.digest.slice(7) : undefined,
      url: a.browser_download_url,
    })),
  };
}

export function buildCatalog(apps, apiReleases) {
  return {
    repo: REPO,
    howToUse: 'apps[].latest is the newest stable release of each app; apps[].releases lists every version, newest first.',
    apps: apps.map(app => {
      const prefix = `${app.id}-v`;
      const releases = apiReleases
        .filter(r => !r.draft && r.tag_name.startsWith(prefix) && /^\d/.test(r.tag_name.slice(prefix.length)))
        .map(r => toRelease(r, r.tag_name.slice(prefix.length)))
        .sort((a, b) => compareVersions(b.version, a.version));
      return {
        ...app,
        page: `https://github.com/${REPO}/tree/main/apps/${app.id}`,
        latest: releases.find(r => !r.prerelease) || null,
        releases,
      };
    }),
  };
}

// The installer or package a visitor should click: not the checksum file, not the manual.
export function primaryAsset(release) {
  const files = release?.assets.filter(a => !/^SHA256SUMS/i.test(a.name)) || [];
  return files.find(a => /\.(exe|msi|zip|7z|streamDeckPlugin)$/i.test(a.name)) || files[0] || null;
}

function formatSize(bytes) {
  return bytes >= 1048576 ? `${(bytes / 1048576).toFixed(1)} MB` : `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

const day = iso => (iso || '').slice(0, 10);

export function hubTable(catalog) {
  const rows = catalog.apps.map(app => {
    const asset = primaryAsset(app.latest);
    const download = asset ? `[${asset.name}](${asset.url}) (${formatSize(asset.size)})` : 'Coming soon';
    const latest = app.latest ? `[${app.latest.version}](${app.latest.url})` : '—';
    return `| [${app.title}](apps/${app.id}/) | ${latest} | ${app.platform} | ${download} |`;
  });
  return ['| App | Latest | Platform | Download |', '| --- | --- | --- | --- |', ...rows].join('\n');
}

export function appTable(app) {
  if (!app.releases.length) return '_No release published yet._';
  const rows = app.releases.map(r => {
    const files = r.assets.map(a => `[${a.name}](${a.url})`).join('<br>');
    const label = r.prerelease ? `${r.version} (pre-release)` : r.version;
    return `| [${label}](${r.url}) | ${day(r.publishedAt)} | ${files} |`;
  });
  return ['| Version | Released | Files |', '| --- | --- | --- |', ...rows].join('\n');
}

export function replaceBlock(text, body) {
  const s = text.indexOf(START);
  const e = text.indexOf(END);
  if (s === -1 || e < s) return `${text.trimEnd()}\n\n${START}\n${body}\n${END}\n`;
  return `${text.slice(0, s)}${START}\n${body}\n${text.slice(e)}`;
}

async function fetchReleases() {
  if (process.env.RELEASES_FILE) return JSON.parse(fs.readFileSync(process.env.RELEASES_FILE, 'utf8'));
  const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'clearedtocode-catalog' };
  if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
  const all = [];
  for (let page = 1; ; page++) {
    const res = await fetch(`https://api.github.com/repos/${REPO}/releases?per_page=100&page=${page}`, { headers });
    if (!res.ok) throw new Error(`GitHub API ${res.status}: ${await res.text()}`);
    const batch = await res.json();
    all.push(...batch);
    if (batch.length < 100) return all;
  }
}

function write(file, text) {
  const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (old !== text) { fs.writeFileSync(file, text); console.log(`updated ${path.relative(root, file)}`); }
}

async function main() {
  const catalog = buildCatalog(loadApps(), await fetchReleases());
  write(path.join(root, 'catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);
  const readme = path.join(root, 'README.md');
  write(readme, replaceBlock(fs.readFileSync(readme, 'utf8'), hubTable(catalog)));
  for (const app of catalog.apps) {
    const file = path.join(root, 'apps', app.id, 'README.md');
    const text = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : `# ${app.title}\n\n${app.summary}\n\n## Downloads\n`;
    write(file, replaceBlock(text, appTable(app)));
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main().catch(err => { console.error(err.message); process.exit(1); });
}
